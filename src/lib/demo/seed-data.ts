/** The JSON payload reset_demo(p_seed jsonb) expects. */
export function buildSeedPayload() {
  return {
    profiles: [
      {
        id: SEED_PEMA.id,
        role: "entrepreneur",
        full_name: SEED_PEMA.full_name,
        phone: null,
        location: SEED_PEMA.location,
        preferred_language: SEED_PEMA.preferred_language,
      },
      {
        id: SEED_YDF_ADMIN.id,
        role: "ydf_admin",
        full_name: SEED_YDF_ADMIN.full_name,
        phone: null,
        location: SEED_YDF_ADMIN.location,
        preferred_language: SEED_YDF_ADMIN.preferred_language,
      },
      ...SEED_MENTORS.map((m) => ({
        id: m.id,
        role: "mentor",
        full_name: m.full_name,
        phone: null,
        location: m.location,
        preferred_language: m.languages.includes("dz") ? "dz" : "en",
      })),
    ],
    entrepreneur_profiles: [
      {
        user_id: SEED_PEMA.id,
        business_name: SEED_PEMA.business_name,
        languages: SEED_PEMA.languages,
        budget: SEED_PEMA.budget,
      },
    ],
    mentor_profiles: SEED_MENTORS.map((m) => ({
      user_id: m.id,
      headline: m.headline,
      bio: m.bio,
      expertise: m.expertise,
      sectors: m.sectors,
      business_stages: m.business_stages,
      languages: m.languages,
      fee: m.fee,
      slots_remaining: m.slots_remaining,
      availability_summary: m.availability_summary,
      sessions_delivered: m.sessions_delivered,
      verified: m.verified,
      active: m.active,
    })),
    resources: SEED_RESOURCES,
    sponsorship_credits: [SEED_CREDIT],
  };
}
